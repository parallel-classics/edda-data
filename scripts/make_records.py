def commons_url(fname):
    f = fname.replace(" ", "_")
    m = hashlib.md5(f.encode("utf-8")).hexdigest()
    return f"https://upload.wikimedia.org/wikipedia/commons/{m[0]}/{m[:2]}/{quote(f)}"


def page_url(fname):
    return "https://commons.wikimedia.org/wiki/File:" + quote(fname.replace(" ", "_"))


def rec(slot, fname, w, h, title, artist, dates, date, medium, source, basis, caption, note="", alts=()):
    part = {"p": "prologue", "g": "gylfaginning", "s": "skaldskaparmal", "h": "hattatal"}[slot[0]]
    chapter = int(slot.split("-c")[1])
    return {
        "id": slot, "part": part, "chapter": chapter,
        "title": title, "artist": artist, "artist_dates": dates, "date": date, "medium": medium,
        "source": source,
        "commons_file": fname, "source_url": page_url(fname), "file_url": commons_url(fname),
        "width": w, "height": h,
        "license": "Public domain", "license_basis": basis,
        "checked_by": CHECKED, "checked_on": TODAY,
        "caption": caption, "note": note,
        "alternatives": [dict(a) for a in alts],
    }


